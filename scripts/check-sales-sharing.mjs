import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { SignJWT } from 'jose';
const base = process.env.SALES_TEST_URL || 'http://localhost:3107';
const key = new TextEncoder().encode(process.env.AUTH_SECRET);
const session = await new SignJWT({}).setProtectedHeader({ alg: 'HS256' }).setExpirationTime('5m').sign(key);
const headers = { Cookie: 'veg_basket_session=' + session };
const request = async (path, options = {}) => {
  const response = await fetch(base + path, { ...options, headers: { ...headers, ...options.headers } });
  assert.equal(response.ok, true, 'Request failed: ' + path + ' (' + response.status + ')');
  return response.json();
};
assert.equal((await fetch(base + '/api/sales')).status, 401);
assert.equal((await fetch(base + '/api/shared-invoices/invalid')).status, 404);
const expired = await new SignJWT({ saleId: '00000000-0000-0000-0000-000000000000' }).setProtectedHeader({ alg: 'HS256' }).setAudience('invoice-share').setExpirationTime(1).sign(key);
assert.equal((await fetch(base + '/api/shared-invoices/' + expired)).status, 404);
const rows = await request('/api/sales');
assert.ok(rows.length, 'Need an existing invoice to verify PDF sharing.');
const sale = await request('/api/sales/' + rows[0].id);
assert.ok(sale.items.every(item => item.itemName === item.itemName.toUpperCase()), 'Invoice names must be uppercase.');
assert.ok(sale.items.every(item => item.itemName), 'Existing invoice item names must remain available.');
const ledger = await request('/api/customers/' + sale.customerId);
const expected = Number(ledger.customer.openingBalance) + ledger.sales.reduce((n, s) => n + Number(s.total) - Number(s.paid), 0) - ledger.payments.filter(p => !p.saleId).reduce((n, p) => n + Number(p.amount), 0);
assert.ok(Math.abs(ledger.summary.outstanding - expected) < 0.005);
const link = await request('/api/sales/' + sale.id + '/share', { method: 'POST' });
const pdf = await fetch(base + link.path);
assert.equal(pdf.status, 200);
assert.equal(pdf.headers.get('content-type'), 'application/pdf');
assert.match(pdf.headers.get('cache-control'), /no-store/);
const pdfBytes = Buffer.from(await pdf.arrayBuffer());
assert.equal(pdfBytes.subarray(0, 5).toString(), '%PDF-');
const pdfText = execFileSync('pdftotext', ['-', '-'], { input: pdfBytes }).toString().replace(/\s+/g, ' ');
for (const item of sale.items) assert.ok(pdfText.includes(item.itemName.replace(/\s+/g, ' ')), 'PDF must contain uppercase item names.');
const invalid = await fetch(base + '/api/sales', { method: 'POST', headers: { ...headers, 'Content-Type': 'application/json' }, body: JSON.stringify({ customerId: sale.customerId, date: sale.saleDate, items: [{ itemName: ' ', quantity: '1', lineTotal: '10' }] }) });
assert.equal(invalid.status, 400);
console.log('Passed: authentication, expired/invalid links, actual ledger balance, legacy item names, shared PDF rendering and invalid manual entry.');
